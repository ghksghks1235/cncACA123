-- 씨앤씨 공용 일정. 기존 출석부와 진도 자료는 변경하지 않습니다.
begin;
create table if not exists public.academy_events (
 id bigint generated by default as identity primary key,
 event_date date not null,
 title text not null check (length(btrim(title)) between 1 and 120),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 created_by text not null,
 updated_by text not null,
 deleted_at timestamptz
);
create index if not exists academy_events_date_idx on public.academy_events(event_date) where deleted_at is null;
alter table public.academy_events enable row level security;
revoke all on public.academy_events from anon, authenticated;
grant select,insert,update on public.academy_events to anon;
grant usage,select on sequence public.academy_events_id_seq to anon;
drop policy if exists academy_events_shared on public.academy_events;
create policy academy_events_shared on public.academy_events for all to anon using (true) with check (true);
create or replace function public.guard_academy_event() returns trigger
language plpgsql set search_path=public as $$
begin
 if not exists(select 1 from public.teachers where code=new.updated_by and active=true) then raise exception '선생님 기호를 확인해주세요.'; end if;
 if tg_op='UPDATE' then new.created_at:=old.created_at;new.created_by:=old.created_by;
 else new.created_at:=clock_timestamp();new.created_by:=new.updated_by;end if;
 new.title:=btrim(new.title);new.updated_at:=clock_timestamp();return new;
end;
$$;
drop trigger if exists academy_event_guard on public.academy_events;
create trigger academy_event_guard before insert or update on public.academy_events for each row execute function public.guard_academy_event();
revoke execute on function public.guard_academy_event() from public,anon,authenticated;
commit;
select '씨앤씨 일정 준비 완료' as result;
